class SIMDAssemblyGenerator:
    def __init__(self):
        self.tests = SIMD_TESTS
    
    def generate_test_file(self, test: SIMDTest, output_path: str):
        """Generate a test file for a SIMD operation"""
        with open(output_path, 'w') as f:
            f.write(f"// {test.name}: {test.description}\n")
            f.write("// Generated by simd_asm_generator.py\n\n")
            f.write(test.c_source)
            f.write("\n")
            f.write(f"// Expected assembly:\n")
            for line in test.expected_asm_snippet.strip().split('\n'):
                f.write(f"//   {line}\n")
    
    def generate_all_tests(self, output_dir: str):
        """Generate all test files"""
        os.makedirs(output_dir, exist_ok=True)
        
        for test in self.tests:
            filename = f"simd_{test.name}.c"
            filepath = os.path.join(output_dir, filename)
            self.generate_test_file(test, filepath)
            print(f"Generated: {filepath}")
    
    def compare_assembly(self, actual_file: str, expected_file: str) -> List[str]:
        """Compare actual assembly with expected"""
        issues = []
        
        try:
            with open(actual_file, 'r') as f:
                actual = f.read()
            
            with open(expected_file, 'r') as f:
                expected = f.read()
            
            # Check for expected instructions
            for test in self.tests:
                for instr in test.instructions:
                    if instr not in actual:
                        issues.append(f"Missing instruction: {instr}")
            
            # Check for XMM register usage
            import re
            xmm_pattern = re.compile(r'xmm\d+')
            xmm_in_actual = xmm_pattern.findall(actual)
            
            if not xmm_in_actual:
                issues.append("No XMM registers found in assembly")
            
        except IOError as e:
            issues.append(f"Error reading files: {e}")
        
        return issues
    
    def generate_expected_asm(self, test_name: str) -> Optional[str]:
        """Get expected assembly for a test"""
        for test in self.tests:
            if test.name == test_name:
                return test.expected_asm_snippet
        return None
    
    def generate_report(self) -> str:
        """Generate test coverage report"""
        lines = []
        lines.append("=" * 70)
        lines.append("SIMD Assembly Test Coverage")
        lines.append("=" * 70)
        
        # Group by instruction type
        by_instruction = {}
        for test in self.tests:
            for instr in test.instructions:
                if instr not in by_instruction:
                    by_instruction[instr] = []
                by_instruction[instr].append(test.name)
        
        lines.append("\nInstructions Covered:")
        lines.append("-" * 70)
        
        for instr, tests in sorted(by_instruction.items()):
            lines.append(f"\n{instr}:")
            for test_name in tests:
                test = next(t for t in self.tests if t.name == test_name)
                lines.append(f"  - {test.description}")
        
        lines.append(f"\nTotal Tests: {len(self.tests)}")
        lines.append(f"Unique Instructions: {len(by_instruction)}")
        
        lines.append("=" * 70)
        return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(
        description='Generate SIMD assembly test cases for ZeroCC'
    )
    parser.add_argument('--generate-all', action='store_true',
                       help='Generate all test files')
    parser.add_argument('--generate', metavar='NAME',
                       help='Generate specific test')
    parser.add_argument('--compare', nargs=2, metavar=('ACTUAL', 'EXPECTED'),
                       help='Compare assembly files')
    parser.add_argument('--output-dir', metavar='DIR', default='/tmp/simd_tests',
                       help='Output directory for generated tests')
    parser.add_argument('--report', action='store_true',
                       help='Show test coverage report')
    
    args = parser.parse_args()
    
    generator = SIMDAssemblyGenerator()
    
    if args.generate_all:
        generator.generate_all_tests(args.output_dir)
    
    elif args.generate:
        for test in generator.tests:
            if test.name == args.generate:
                filepath = os.path.join(args.output_dir, f"simd_{test.name}.c")
                os.makedirs(args.output_dir, exist_ok=True)
                generator.generate_test_file(test, filepath)
                print(f"Generated: {filepath}")
                break
        else:
            print(f"Unknown test: {args.generate}")
            print("Available tests:")
            for test in generator.tests:
                print(f"  - {test.name}: {test.description}")
    
    elif args.compare:
        issues = generator.compare_assembly(args.compare[0], args.compare[1])
        if issues:
            print("Issues found:")
            for issue in issues:
                print(f"  - {issue}")
            sys.exit(1)
        else:
            print("No issues found!")
    
    elif args.report:
        print(generator.generate_report())
    
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == '__main__':
    main()
