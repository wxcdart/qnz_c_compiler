/* far_thunk.c - own-linker far-rel32 thunk pool (detour-style).
 *
 * Two synthetic-object fixtures exercise the x86-64 linker's handling of
 * 32-bit relative relocations whose final delta is outside +-2GB:
 *
 *  (A) a `call far_fn` (PLT32/PC32) whose target sits ~3GB past the end of
 *      .text (in a 4GB .bss of a second object): the linker must install a
 *      14-byte `ff 25 00 00 00 00` + abs64 thunk in the pool reserved at
 *      the end of .text and re-aim the call at it.  The call is placed
 *      after `ret` so the binary runs fine without ever executing it.
 *
 *  (B) a rip-relative DATA reference (lea) to the same far symbol: the
 *      re-aim cannot preserve semantics (an executed thunk is not a value
 *      source), so the link must fail with a clean, actionable error
 *      instead of silently truncating the displacement.
 *
 * The pre-thunk linker wrote `d = S + A - P` unconditionally, i.e. it
 * silently wrapped the displacement and produced a broken binary for
 * case (A); this test pins both behaviors.
 */
