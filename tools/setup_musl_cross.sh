#!/bin/bash
# setup_musl_cross.sh -- build & install a STATIC MUSL cross toolchain for one ISA.
#
# Produces, under $PREFIX_ROOT/<arch>/ (default /home/ubuntu/dev/musl-cross/<arch>):
#   include/  lib/            the static musl libc.a + crt + headers
#   musl-gcc.specs            gcc specs overriding startfile/endfile/link_libgcc
# and a wrapper at $BINDIR/musl-gcc-<arch> (default /home/ubuntu/.local/bin):
#   musl-gcc-<arch> -- a fully STATIC musl binary for <arch> via the system cross gcc.
#
# x86_64/aarch64/riscv64 use a specs-based wrapper (the cross gcc ships a same-arch
# libgcc). riscv32 is special-cased: the Debian riscv64 cross gcc only ships an rv64
# libgcc (referenced by absolute path), so this script additionally builds a small
# rv32 libgcc shim (correct 64-bit div/mod + float128 link-stubs) and emits an
# explicit-link wrapper that links musl crt + libc + the shim in the correct order.
#
# Usage:
#   setup_musl_cross.sh --arch <arch> --ccbin <cross-gcc> [--extra "flags"]
#                       [--host <gcc-tuple>] [--prefix-root DIR] [--bindir DIR]
#
# Examples:
#   --arch aarch64 --ccbin aarch64-linux-gnu-gcc
#   --arch riscv64 --ccbin riscv64-linux-gnu-gcc
#   --arch riscv32 --ccbin riscv64-linux-gnu-gcc --extra "-march=rv32gc -mabi=ilp32" --host riscv32-linux-musl

set -euo pipefail

ARCH=""; CCBIN=""; EXTRA=""; HOST=""; PREFIX_ROOT="/home/ubuntu/dev/musl-cross"; BINDIR="/home/ubuntu/.local/bin"
while [ $# -gt 0 ]; do case "$1" in
  --arch)  ARCH="$2"; shift 2;;
  --ccbin) CCBIN="$2"; shift 2;;
  --extra) EXTRA="$2"; shift 2;;
  --host)  HOST="$2"; shift 2;;
  --prefix-root) PREFIX_ROOT="$2"; shift 2;;
  --bindir)  BINDIR="$2"; shift 2;;
  -h|--help) grep '^#' "$0" | sed 's/^#//;s/^ //'; exit 0;;
  *) echo "unknown arg: $1" >&2; exit 2;;
esac; done
[ -n "$ARCH" ] && [ -n "$CCBIN" ] || { echo "need --arch and --ccbin" >&2; exit 2; }
[ -n "$HOST" ] || HOST="${ARCH}-linux-musl"

MUSL_SRC="${MUSL_SRC:-/home/ubuntu/dev/qnz_gcc/third_party/musl/musl-1.2.6}"
PREFIX="$PREFIX_ROOT/$ARCH"
BUILD="$(mktemp -d /tmp/muslbuild_$ARCH.XXXXXX)"

command -v "$CCBIN" >/dev/null || { echo "cross gcc '$CCBIN' not found" >&2; exit 1; }
[ -d "$MUSL_SRC" ] || { echo "musl source not found at $MUSL_SRC" >&2; exit 1; }

echo "==> building static musl for $ARCH ($CCBIN $EXTRA, host=$HOST)"
rm -rf "$BUILD"; cp -r "$MUSL_SRC" "$BUILD"; cd "$BUILD"; rm -rf obj lib
CC="$CCBIN $EXTRA" ./configure --build=x86_64-linux-gnu --host="$HOST" \
  --prefix="$PREFIX" --syslibdir="$PREFIX/lib" --disable-shared --enable-optimize >/dev/null 2>&1
make -j"$(nproc)" AR=ar RANLIB=ranlib STRIP=strip
make install AR=ar RANLIB=ranlib STRIP=strip >/dev/null 2>&1
objarch=$(readelf -h obj/src/string/strlen.lo 2>/dev/null | awk -F': ' '/Machine/{print $2}' | tr -d ' ')
echo "    musl $ARCH: libc.a built (object arch: ${objarch:-?})"

# --- specs: full musl-gcc.specs (proven working structure). The empty *esp_*
# --- sections stop gcc from injecting its default glibc start files (which would
# --- otherwise override *startfile); -nostdlib + -dynamic-linker live in *link.
cat > "$PREFIX/musl-gcc.specs" <<EOF
%rename cpp_options old_cpp_options

*cpp_options:
-nostdinc -isystem $PREFIX/include -isystem include%s %(old_cpp_options)

*cc1:
%(cc1_cpu) -nostdinc -isystem $PREFIX/include -isystem include%s

*link_libgcc:
-L$PREFIX/lib -L .%s

*libgcc:
libgcc.a%s %:if-exists(libgcc_eh.a%s)

*startfile:
%{!shared: $PREFIX/lib/Scrt1.o} $PREFIX/lib/crti.o crtbeginS.o%s

*endfile:
crtendS.o%s $PREFIX/lib/crtn.o

*link:
-dynamic-linker $PREFIX/lib/ld-musl-$ARCH.so.1 -nostdlib %{shared:-shared} %{static:-static} %{rdynamic:-export-dynamic}

*esp_link:

*esp_options:

*esp_cpp_options:
EOF
# gcc's specs reader rejects an empty-valued spec at EOF; a trailing blank line
# (two newlines) after the final empty *esp_cpp_options: is required.
printf '\n\n' >> "$PREFIX/musl-gcc.specs"

# --- generic wrapper (specs carry -nostdinc/-isystem/crt/libc; wrapper adds arch + -specs) ---
mkdir -p "$BINDIR"
cat > "$BINDIR/musl-gcc-$ARCH" <<EOF
#!/bin/sh
# static-musl cross compiler for $ARCH (auto-generated by setup_musl_cross.sh)
# usage: musl-gcc-$ARCH -static -O2 prog.c -o out [-lc]
exec $CCBIN $EXTRA "\$@" -specs $PREFIX/musl-gcc.specs
EOF

# --- riscv32: cross gcc hardcodes its rv64 libgcc by absolute path (ABI-incompatible
# --- with elf32), so build a small rv32 libgcc shim and use an explicit-link wrapper.
if [ "$ARCH" = "riscv32" ]; then
  SHIM="$BUILD/shim.c"
  cat > "$SHIM" <<'SHIM_EOF'
/* rv32 libgcc shim for the static-musl cross reference.
 * The Debian riscv64 cross toolchain ships only an rv64 libgcc, so a static
 * musl rv32 build that uses printf is missing these libgcc helpers.
 *   - __udivdi3 / __umoddi3: correct software 64-bit div/mod.
 *   - the __tf2 (long double / __float128) helpers: only ever *called* for
 *     long-double printf, which the isa_qemu battery never does. They abort
 *     loudly if reached (a full rv32 toolchain would supply real ones).
 */
#include <stdint.h>
static uint64_t __udivmoddi3(uint64_t u, uint64_t v, int *rem) {
    uint64_t q = 0, r = 0;
    for (int i = 63; i >= 0; i--) {
        r = (r << 1) | ((u >> i) & 1);
        if (r >= v) { r -= v; q |= (uint64_t)1 << i; }
    }
    if (rem) *rem = (int)r;
    return q;
}
uint64_t __udivdi3(uint64_t u, uint64_t v) { return __udivmoddi3(u, v, 0); }
uint64_t __umoddi3(uint64_t u, uint64_t v) { int r; (void)__udivmoddi3(u, v, &r); return (uint64_t)r; }
static void __trap(void) { __builtin_trap(); }
long double __addtf3(long double a, long double b)  { (void)a;(void)b; __trap(); }
long double __subtf3(long double a, long double b)  { (void)a;(void)b; __trap(); }
long double __multf3(long double a, long double b)  { (void)a;(void)b; __trap(); }
int         __netf2(long double a, long double b)   { (void)a;(void)b; __trap(); }
long double __extenddftf2(double a)                 { (void)a; __trap(); }
long        __fixtfsi(long double a)                { (void)a; __trap(); }
unsigned long __fixunstfsi(long double a)           { (void)a; __trap(); }
long double __floatsitf(int a)                      { (void)a; __trap(); }
long double __floatunsitf(unsigned int a)           { (void)a; __trap(); }
SHIM_EOF
  "$CCBIN" $EXTRA -O2 -nostdinc -isystem "$PREFIX/include" -c "$SHIM" -o "$BUILD/shim.o"
  rm -f "$PREFIX/lib/libgcc.a"
  ( cd "$PREFIX/lib" && ar rc libgcc.a "$BUILD/shim.o" && ranlib libgcc.a )
  echo "    built rv32 libgcc shim -> $PREFIX/lib/libgcc.a"
  cat > "$BINDIR/musl-gcc-$ARCH" <<'RVEOF'
#!/bin/bash
# static-musl rv32 cross compiler (auto-generated by setup_musl_cross.sh).
# The Debian riscv64 cross gcc hardcodes its rv64 libgcc by absolute path, so we
# compile the source(s) and do an EXPLICIT static link: musl crt + user objects +
# musl libc + the rv32 libgcc shim + musl crtn, in the correct order.
P=__PREFIX__
CC="riscv64-linux-gnu-gcc"; AF="-march=rv32gc -mabi=ilp32"; INC="-nostdinc -isystem $P/include"
CFLAGS=(); SRCS=(); OUT=""; prev=""
for a in "$@"; do
  if [ "$prev" = "-o" ]; then OUT="$a"; prev=""; continue; fi
  case "$a" in
    -o) prev="-o" ;;
    *.c) SRCS+=("$a") ;;
    -static|-lc) : ;;
    *) CFLAGS+=("$a") ;;
  esac
done
[ -n "$OUT" ] || OUT=a.out
[ ${#SRCS[@]} -ge 1 ] || { echo "musl-gcc-riscv32: no .c source" >&2; exit 2; }
tmp=$(mktemp -d); i=0
for s in "${SRCS[@]}"; do i=$((i+1)); "$CC" $AF $INC "${CFLAGS[@]}" -c "$s" -o "$tmp/obj$i.o" || { rm -rf "$tmp"; exit 1; }; done
"$CC" $AF -static -no-pie -Wl,-m,elf32lriscv -nostdlib \
  "$P/lib/Scrt1.o" "$P/lib/crti.o" "$tmp"/obj*.o "$P/lib/libc.a" "$P/lib/libgcc.a" "$P/lib/crtn.o" \
  -o "$OUT"
rc=$?; rm -rf "$tmp"; exit $rc
RVEOF
  sed -i "s#__PREFIX__#$PREFIX#g" "$BINDIR/musl-gcc-$ARCH"
fi

chmod +x "$BINDIR/musl-gcc-$ARCH"
echo "    installed $BINDIR/musl-gcc-$ARCH"
echo "    prefix: $PREFIX"
