static int write_file(const char *path, const uint8_t *data, size_t n) {
    FILE *f = fopen(path, "wb");
    if (!f) return -1;
    if (fwrite(data, 1, n, f) != n) { fclose(f); return -1; }
    fclose(f);
    return 0;
}

/* Read a file fully; returns a malloc'd buffer, sets *len. */
static uint8_t *read_file(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t *buf = (uint8_t *)malloc((size_t)n);
    if (!buf || fread(buf, 1, (size_t)n, f) != (size_t)n) {
        free(buf);
        fclose(f);
        return NULL;
    }
    fclose(f);
    *len = (size_t)n;
    return buf;
}

static uint64_t rd64(const uint8_t *p) {
    uint64_t v = 0;
    for (int i = 7; i >= 0; i--) v = (v << 8) | p[i];
    return v;
}
static int32_t rd32s(const uint8_t *p) { return (int32_t)rd64(p); }

/* Find a section by name in an ET_EXEC; fills vma/offset/size.  Returns 1
 * on success (0 if absent). */
static int find_sec(const uint8_t *img, size_t len, const char *name,
                    uint64_t *vma, uint64_t *off, uint64_t *size) {
    if (len < 64 || img[0] != 0x7f) return 0;
    uint64_t shoff = rd64(img + 40);
    uint16_t shnum = (uint16_t)(img[60] | (img[61] << 8));
    uint16_t shstrndx = (uint16_t)(img[62] | (img[63] << 8));
    if (shoff + (uint64_t)shnum * 64 > len) return 0;
    const uint8_t *sh = img + shoff;
    const uint8_t *shstr = NULL;
    if (shstrndx < shnum) {
        uint64_t shstr_off = rd64(sh + (uint64_t)shstrndx * 64 + 24);
        if (shstr_off < len) shstr = img + shstr_off;
    }
    if (!shstr) return 0;
    for (uint16_t i = 0; i < shnum; i++) {
        const uint8_t *h = sh + (uint64_t)i * 64;
        uint32_t name_idx = (uint32_t)(h[0] | (h[1] << 8) | (h[2] << 16) |
                                        ((uint32_t)h[3] << 24));
        const char *nm = (const char *)(shstr + name_idx);
        if (nm[0] == '\0' || strcmp(nm, name) != 0) continue;
        if (vma) *vma = rd64(h + 16);
        if (off) *off = rd64(h + 24);
        if (size) *size = rd64(h + 32);
        return 1;
    }
    return 0;
}

int main(void) {
    int fails = 0;

    /* ---- fixture A: far call -> thunk, binary runs ---- */
    const char *Aa = "/tmp/zc_far_thunk_Aa.o";
    const char *Ab = "/tmp/zc_far_thunk_Ab.o";
    const char *Abn = "/tmp/zc_far_thunk_A.bin";
    if (write_file(Aa, ftA_a, ftA_a_len) || write_file(Ab, ftA_b, ftA_b_len)) {
        fprintf(stderr, "cannot write fixture A\n");
        return 1;
    }
    char err[1024] = {0};
    const char *objsA[2] = { Aa, Ab };
    if (zero_cc_link_exec(Abn, objsA, 2, NULL, 0, NULL, err, sizeof(err)) != 0) {
        fprintf(stderr, "FAIL(A): link: %s\n", err);
        return 1;
    }
    int rc = system(Abn);
    if (rc != 0) {
        fprintf(stderr, "FAIL(A): binary exit=%d\n", rc);
        fails++;
    }
    /* Byte-level verification of the thunk. */
    size_t len = 0;
    uint8_t *img = read_file(Abn, &len);
    if (!img) {
        fprintf(stderr, "FAIL(A): cannot read linked binary\n");
        return 1;
    }
    uint64_t t_v, t_o, t_s, b_v;
    if (!find_sec(img, len, ".text", &t_v, &t_o, &t_s) ||
        !find_sec(img, len, ".bss", &b_v, NULL, NULL)) {
        fprintf(stderr, "FAIL(A): cannot find .text/.bss in output\n");
        return 1;
    }
    uint64_t expected_target = b_v + 3ull * 1024 * 1024 * 1024;
    int found = 0;
    uint64_t thunk_vma = 0;
    for (uint64_t p = 0; p + 14 <= t_s; p++) {
        const uint8_t *q = img + t_o + p;
        if (q[0] == 0xff && q[1] == 0x25 && !q[2] && !q[3] && !q[4] && !q[5]) {
            if (rd64(q + 6) == expected_target) {
                found = 1;
                thunk_vma = t_v + p;
                break;
            }
        }
    }
    if (!found) {
        fprintf(stderr, "FAIL(A): no thunk with target 0x%lx in .text\n",
                (unsigned long)expected_target);
        fails++;
    } else {
        /* The call site: the stub owns .text[0..16); a.o's bytes start at
         * +16, so e8 is at +17 and the displacement at +18. */
        const uint8_t *e8 = img + t_o + 16 + 1;
        if (e8[0] != 0xe8) {
            fprintf(stderr, "FAIL(A): expected e8 at .text+17, got 0x%02x\n",
                    e8[0]);
            fails++;
        } else {
            int32_t d = rd32s(e8 + 1);
            uint64_t call_target = (t_v + 16 + 1) + 5 + (int64_t)d;
            if (call_target != thunk_vma) {
                fprintf(stderr,
                        "FAIL(A): call targets 0x%lx, thunk at 0x%lx\n",
                        (unsigned long)call_target, (unsigned long)thunk_vma);
                fails++;
            }
        }
    }
    free(img);

    /* ---- fixture B: far lea -> clean link error ---- */
    const char *Ba = "/tmp/zc_far_thunk_Ba.o";
    const char *Bb = "/tmp/zc_far_thunk_Bb.o";
    const char *Bbn = "/tmp/zc_far_thunk_B.bin";
    if (write_file(Ba, ftB_a, ftB_a_len) || write_file(Bb, ftB_b, ftB_b_len)) {
        fprintf(stderr, "cannot write fixture B\n");
        return 1;
    }
    const char *objsB[2] = { Ba, Bb };
    char errB[1024] = {0};
    int rcB = zero_cc_link_exec(Bbn, objsB, 2, NULL, 0, NULL, errB, sizeof(errB));
    if (rcB == 0) {
        fprintf(stderr, "FAIL(B): far lea linked (should be a clean error)\n");
        fails++;
    } else if (strstr(errB, "rip-relative data reference") == NULL) {
        fprintf(stderr, "FAIL(B): unexpected error: %s\n", errB);
        fails++;
    }

    if (fails == 0) {
        printf("far_thunk ok\n");
        return 0;
    }
    return 1;
}
