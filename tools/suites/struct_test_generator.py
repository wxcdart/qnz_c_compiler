#!/usr/bin/env python3
"""
Struct Test Generator for ZeroCC - Phase 2

Generates comprehensive test cases for struct argument passing and return values
according to System V AMD64 ABI specification.

Generated tests cover:
- 1-chunk structs (1-8 bytes): passed/returned in RDI/RAX
- 2-chunk structs (9-16 bytes): passed/returned in RDI:RSI / RAX:RDX
- 3+ chunk structs (>16 bytes): passed/returned via hidden pointer
- Mixed argument types
- Nested structs
- Struct arrays

Usage:
    python3 tools/struct_test_generator.py --output test_structs.c
    python3 tools/struct_test_generator.py --mode args --output test_struct_args.c
    python3 tools/struct_test_generator.py --mode returns --output test_struct_returns.c
    python3 tools/struct_test_generator.py --mode comprehensive --output test_structs_full.c
"""

import argparse
import sys
from pathlib import Path
from typing import List, Dict, Optional

# Test case templates
TEST_TEMPLATES = {
    'header': """/* Struct Test Cases - Generated by struct_test_generator.py */
/* System V AMD64 ABI Compliance Tests */

#include <assert.h>
#include <stdio.h>

""",
    
    '1_chunk_struct_def': """/* 1-chunk struct (4-8 bytes) - passed in RDI, returned in RAX */
typedef struct {{
    {members}
}} {name};

""",
    
    '2_chunk_struct_def': """/* 2-chunk struct (9-16 bytes) - passed in RDI:RSI, returned in RAX:RDX */
typedef struct {{
    {members}
}} {name};

""",
    
    '3_chunk_struct_def': """/* 3+ chunk struct (>16 bytes) - passed via hidden pointer */
typedef struct {{
    {members}
}} {name};

""",
    
    'take_1_chunk': """/* Take 1-chunk struct by value */
int take_{name}({name} s) {{
    return {return_expr};
}}

""",
    
    'make_1_chunk': """/* Make 1-chunk struct by value */
{name} make_{name}({params}) {{
    {name} s = {{ {init} }};
    return s;
}}

""",
    
    'take_2_chunk': """/* Take 2-chunk struct by value */
int take_{name}({name} s) {{
    return {return_expr};
}}

""",
    
    'make_2_chunk': """/* Make 2-chunk struct by value */
{name} make_{name}({params}) {{
    {name} s = {{ {init} }};
    return s;
}}

""",
    
    'take_3_chunk': """/* Take 3+ chunk struct by value */
int take_{name}({name} s) {{
    return {return_expr};
}}

""",
    
    'make_3_chunk': """/* Make 3+ chunk struct by value */
{name} make_{name}({params}) {{
    {name} s = {{ {init} }};
    return s;
}}

""",
    
    'test_1_chunk': """    /* Test 1-chunk struct */
    {{
        {name} s = make_{name}({args});
        assert(take_{name}(s) == {expected});
    }}

""",
    
    'test_2_chunk': """    /* Test 2-chunk struct */
    {{
        {name} s = make_{name}({args});
        assert(take_{name}(s) == {expected});
    }}

""",
    
    'test_3_chunk': """    /* Test 3+ chunk struct */
    {{
        {name} s = make_{name}({args});
        assert(take_{name}(s) == {expected});
    }}

""",
    
    'main_template': """int main(void) {{
{tests}
    return 0;
}}
""",
}


class StructTestGenerator:
    """Generator for struct test cases."""
    
    def __init__(self):
        self.structs = []
        self.functions = []
        self.tests = []
    
    def add_1_chunk_struct(self, name: str, members: List[str], 
                           param_names: List[str], return_expr: str):
        """Add a 1-chunk struct (4-8 bytes)."""
        struct_def = TEST_TEMPLATES['1_chunk_struct_def'].format(
            name=name,
            members='\n    '.join(members)
        )
        self.structs.append(struct_def)
        
        # Generate take function
        take_func = TEST_TEMPLATES['take_1_chunk'].format(
            name=name,
            return_expr=return_expr
        )
        self.functions.append(take_func)
        
        # Generate make function
        params = ', '.join([f'int {n}' for n in param_names])
        init = ', '.join(param_names)
        make_func = TEST_TEMPLATES['make_1_chunk'].format(
            name=name,
            params=params,
            init=init
        )
        self.functions.append(make_func)
        
        # Generate test
        args = ', '.join([str(i+1) for i in range(len(param_names))])
        test = TEST_TEMPLATES['test_1_chunk'].format(
            name=name,
            args=args,
            expected=return_expr
        )
        self.tests.append(test)
    
    def add_2_chunk_struct(self, name: str, members: List[str],
                           param_names: List[str], return_expr: str):
        """Add a 2-chunk struct (9-16 bytes)."""
        struct_def = TEST_TEMPLATES['2_chunk_struct_def'].format(
            name=name,
            members='\n    '.join(members)
        )
        self.structs.append(struct_def)
        
        # Generate take function
        take_func = TEST_TEMPLATES['take_2_chunk'].format(
            name=name,
            return_expr=return_expr
        )
        self.functions.append(take_func)
        
        # Generate make function
        params = ', '.join([f'int {n}' for n in param_names])
        init = ', '.join(param_names)
        make_func = TEST_TEMPLATES['make_2_chunk'].format(
            name=name,
            params=params,
            init=init
        )
        self.functions.append(make_func)
        
        # Generate test
        args = ', '.join([str(i+1) for i in range(len(param_names))])
        test = TEST_TEMPLATES['test_2_chunk'].format(
            name=name,
            args=args,
            expected=return_expr
        )
        self.tests.append(test)
    
    def add_3_chunk_struct(self, name: str, members: List[str],
                           param_names: List[str], return_expr: str):
        """Add a 3+ chunk struct (>16 bytes)."""
        struct_def = TEST_TEMPLATES['3_chunk_struct_def'].format(
            name=name,
            members='\n    '.join(members)
        )
        self.structs.append(struct_def)
        
        # Generate take function
        take_func = TEST_TEMPLATES['take_3_chunk'].format(
            name=name,
            return_expr=return_expr
        )
        self.functions.append(take_func)
        
        # Generate make function
        params = ', '.join([f'int {n}' for n in param_names])
        init = ', '.join(param_names)
        make_func = TEST_TEMPLATES['make_3_chunk'].format(
            name=name,
            params=params,
            init=init
        )
        self.functions.append(make_func)
        
        # Generate test
        args = ', '.join([str(i+1) for i in range(len(param_names))])
        test = TEST_TEMPLATES['test_3_chunk'].format(
            name=name,
            args=args,
            expected=return_expr
        )
        self.tests.append(test)
    
    def generate(self, mode: str = 'comprehensive') -> str:
        """Generate complete test file."""
        output = TEST_TEMPLATES['header']
        
        # Add struct definitions
        output += '\n'.join(self.structs)
        
        # Add functions
        output += '\n'.join(self.functions)
        
        # Add main function
        test_body = ''.join(self.tests)
        output += TEST_TEMPLATES['main_template'].format(tests=test_body)
        
        return output


