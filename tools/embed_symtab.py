#!/usr/bin/env python3
"""
tools/embed_symtab.py — Sprint 153 (Host Runtime #11, Phase 1).

Pre-bake the executable's own defined global symbols into a `.rodata`
table consumed by zero_rt/dlfcn/dlfcn.c, so its `dlsym` needs no
`/proc/self/exe` (hardened containers, chroots, sealed /proc).

Design: the generated C does NOT bake absolute addresses — it takes the
address of every symbol *by reference* (an `extern` declaration plus a
`&name` in the initializer), so the addresses are ordinary link-time
relocations. The table is therefore correct after ANY relink with no
two-pass fixpoint, no fixed-size reservation, and no staleness:

    extern void printf(void);      /* function symbol */
    extern char  stdout[];         /* data symbol     */
    const ZeroRtEmbeddedSym g_zero_rt_embedded_syms[] = {
        { "printf", (const void *)&printf },
        { "stdout", &stdout[0] },
        ...
        { 0, 0 }                   /* sentinel */
    };

Build integration (Makefile, `build/bin/zerocc`): the rule links once,
runs this generator against the fresh binary (`--bin $@ --out ...`),
and relinks once if the generator reports a change (exit 3).  A fresh
build (no generated file yet) is bootstrapped by `--emit-empty`, which
links first with a sentinel-only table; the first regeneration fills it
in.  The generator only rewrites its output when the content actually
changes, so an up-to-date build is a no-op.

Symbol selection (matches what `dlsym` can legitimately return from the
process's own namespace):
  - defined (no `U`), global (uppercase nm type: T D B R strong, W V
    weak) — local (lowercase) symbols are unreachable by name;
  - name is a valid C identifier (the generator must emit it as a
    declarator); C keywords cannot occur (C source may not name an
    object or function with a keyword);
  - duplicates (weak/strong pairs in the symtab): strong beats weak,
    first occurrence wins within a class;
  - sorted bytewise by name (strcmp order) — dlfcn.c binary-searches.

Usage:
    embed_symtab.py --emit-empty OUT
    embed_symtab.py --bin ELF --out OUT

Exit codes: 0 = output unchanged (or already correct), 3 = output
rewritten (Makefile relinks), 1 = error.
"""

import argparse
import os
import re
import subprocess
import sys

IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
FUNC_TYPES = {"T", "W"}          # text / weak function
DATA_TYPES = {"D", "B", "R", "V"}  # data / bss / rodata / weak object
# The table's own definitions must not be table entries (they would collide
# with the `const unsigned long g_zero_rt_embedded_sym_count` emitted at the
# end of the generated file).  Excluding them also makes the two-pass link
# converge in one relink.
SELF_SYMBOLS = {"g_zero_rt_embedded_syms", "g_zero_rt_embedded_sym_count"}

HEADER = """\
/* AUTO-GENERATED by tools/embed_symtab.py -- do not edit.
 *
 * Pre-baked global symbol table for zero_rt/dlfcn/dlfcn.c (Sprint 153,
 * Host Runtime #11 Phase 1): `dlsym` on the process's own namespace
 * resolves from this table instead of re-reading /proc/self/exe.
 *
 * Addresses are address-taken references (link-time relocations), so
 * the table is always valid for whatever binary this file is linked
 * into -- no absolute constants, no two-pass fixpoint.
 */

/* The generic `extern void name(void);` declarations disagree with gcc's
 * known builtins (libm: sin, yn, ...); the mismatch is harmless (we only
 * take the address) -- silence it for this translation unit. */
#pragma GCC diagnostic ignored "-Wbuiltin-declaration-mismatch"

typedef struct { const char *name; const void *addr; } ZeroRtEmbeddedSym;

"""


def collect_symbols(elf):
    """Run `nm --defined-only` on ELF; return sorted [(name, is_func)]."""
    out = subprocess.run(
        ["nm", "--defined-only", elf],
        capture_output=True, text=True, check=True)
    best = {}  # name -> (priority, is_func); 0 = strong, 1 = weak
    for line in out.stdout.splitlines():
        parts = line.split(None, 2)
        if len(parts) != 3:
            continue
        _addr, kind, name = parts
        if kind not in FUNC_TYPES and kind not in DATA_TYPES:
            continue  # local (lowercase), undefined, file/section symbols
        if not IDENT_RE.match(name) or name in SELF_SYMBOLS:
            continue
        is_func = kind in FUNC_TYPES
        priority = 0 if kind in {"T", "D", "B", "R"} else 1
        if name not in best or priority < best[name][0]:
            best[name] = (priority, is_func)
    return sorted(((n, f) for n, (_p, f) in best.items()))


def render(symbols):
    lines = [HEADER]
    for name, is_func in symbols:
        if is_func:
            lines.append("extern void %s(void);" % name)
        else:
            lines.append("extern char %s[];" % name)
    lines.append("")
    lines.append("const ZeroRtEmbeddedSym g_zero_rt_embedded_syms[] = {")
    for name, is_func in symbols:
        ref = "(const void *)&%s" % name if is_func else "&%s[0]" % name
        lines.append('    { "%s", %s },' % (name, ref))
    lines.append("    { 0, 0 }")
    lines.append("};")
    lines.append("")
    lines.append("const unsigned long g_zero_rt_embedded_sym_count = %d;"
                 % len(symbols))
    lines.append("")
    return "\n".join(lines)


def write_if_changed(path, content):
    """Write path only when content differs. Return 3 if written, 0 if not."""
    old = None
    if os.path.exists(path):
        with open(path, "r") as f:
            old = f.read()
    if old == content:
        return 0
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(content)
    os.replace(tmp, path)
    return 3


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--emit-empty", metavar="OUT",
                    help="bootstrap: write a sentinel-only table to OUT")
    ap.add_argument("--bin", metavar="ELF",
                    help="ELF binary to extract the symbol table from")
    ap.add_argument("--out", metavar="OUT",
                    help="output .c path (with --bin)")
    a = ap.parse_args()

    if a.emit_empty:
        return write_if_changed(a.emit_empty, render([]))
    if not (a.bin and a.out):
        ap.error("need --bin ELF --out OUT (or --emit-empty OUT)")
    return write_if_changed(a.out, render(collect_symbols(a.bin)))


if __name__ == "__main__":
    sys.exit(main())
