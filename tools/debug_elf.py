#!/usr/bin/env python3
"""
Debug ELF file structure to investigate relocation issues.

This script analyzes ELF files generated by zerocc to identify:
1. Missing relocation sections (.rela.text)
2. External function call patterns
3. Symbol table issues
"""

import sys
import struct
import subprocess
from pathlib import Path

def read_elf_header(data):
    """Parse ELF64 header."""
    if len(data) < 64:
        return None
    
    e_type = struct.unpack('<H', data[16:18])[0]
    e_machine = struct.unpack('<H', data[18:20])[0]
    e_version = struct.unpack('<I', data[20:24])[0]
    e_entry = struct.unpack('<Q', data[24:32])[0]
    e_phoff = struct.unpack('<Q', data[32:40])[0]
    e_shoff = struct.unpack('<Q', data[40:48])[0]
    e_flags = struct.unpack('<I', data[48:52])[0]
    e_ehsize = struct.unpack('<H', data[52:54])[0]
    e_phentsize = struct.unpack('<H', data[54:56])[0]
    e_phnum = struct.unpack('<H', data[56:58])[0]
    e_shentsize = struct.unpack('<H', data[58:60])[0]
    e_shnum = struct.unpack('<H', data[60:62])[0]
    e_shstrndx = struct.unpack('<H', data[62:64])[0]
    
    return {
        'e_type': e_type,
        'e_machine': e_machine,
        'e_entry': e_entry,
        'e_shoff': e_shoff,
        'e_shnum': e_shnum,
        'e_shstrndx': e_shstrndx,
    }

def read_section_headers(data, e_shoff, e_shnum, e_shentsize):
    """Parse section headers."""
    sections = []
    for i in range(e_shnum):
        offset = e_shoff + i * e_shentsize
        shdr = data[offset:offset + e_shentsize]
        
        sh_name = struct.unpack('<I', shdr[0:4])[0]
        sh_type = struct.unpack('<I', shdr[4:8])[0]
        sh_flags = struct.unpack('<Q', shdr[8:16])[0]
        sh_addr = struct.unpack('<Q', shdr[16:24])[0]
        sh_offset = struct.unpack('<Q', shdr[24:32])[0]
        sh_size = struct.unpack('<Q', shdr[32:40])[0]
        sh_link = struct.unpack('<I', shdr[40:44])[0]
        sh_info = struct.unpack('<I', shdr[44:48])[0]
        sh_addralign = struct.unpack('<Q', shdr[48:56])[0]
        sh_entsize = struct.unpack('<Q', shdr[56:64])[0]
        
        sections.append({
            'index': i,
            'sh_name': sh_name,
            'sh_type': sh_type,
            'sh_flags': sh_flags,
            'sh_offset': sh_offset,
            'sh_size': sh_size,
            'sh_link': sh_link,
            'sh_info': sh_info,
            'sh_addralign': sh_addralign,
            'sh_entsize': sh_entsize,
        })
    
    return sections

def get_section_name(data, shstrtab_offset, sh_name):
    """Get section name from string table."""
    start = shstrtab_offset + sh_name
    end = data.find(b'\x00', start)
    if end == -1:
        return "<invalid>"
    return data[start:end].decode('utf-8', errors='replace')

def analyze_external_calls(data, sections):
    """Analyze .text section for external function call patterns."""
    text_section = None
    for sec in sections:
        if sec['sh_type'] == 1:  # SHT_PROGBITS
            # Check if it's the .text section by looking at flags
            if sec['sh_flags'] & 0x4:  # SHF_EXECINSTR
                text_section = sec
                break
    
    if not text_section:
        print("No .text section found")
        return
    
    text = data[text_section['sh_offset']:text_section['sh_offset'] + text_section['sh_size']]
    
    print("\n=== External Call Pattern Analysis ===")
    print(f".text section: offset=0x{text_section['sh_offset']:x}, size=0x{text_section['sh_size']:x}")
    
    # Look for call patterns
    # Direct call: E8 rel32
    # Indirect call via rbx: BB xx xx xx xx xx xx xx xx FF D3
    
    patterns = []
    
    # Find direct calls (E8)
    pos = 0
    while pos < len(text) - 4:
        if text[pos] == 0xE8:
            rel = struct.unpack('<i', text[pos+1:pos+5])[0]
            target = pos + 5 + rel
            patterns.append(('direct_call', pos, target, rel))
        pos += 1
    
    # Find indirect calls via rbx (BB ... FF D3)
    pos = 0
    while pos < len(text) - 10:
        if text[pos] == 0xBB and text[pos+9] == 0xFF and text[pos+10] == 0xD3:
            addr = struct.unpack('<Q', text[pos+1:pos+9])[0]
            patterns.append(('indirect_call_rbx', pos, addr, None))
        pos += 1
    
    for pattern_type, offset, target, rel in patterns:
        if pattern_type == 'direct_call':
            print(f"  Direct call at 0x{offset:x}: rel={rel:+d}, target=0x{target:x}")
        else:
            print(f"  Indirect call (rbx) at 0x{offset:x}: address=0x{target:x}")
            if target == 0:
                print(f"    ⚠️  WARNING: Zero address - external function call not relocated!")

def analyze_relocations(sections):
    """Check for relocation sections."""
    print("\n=== Relocation Section Analysis ===")
    
    reloc_types = {
        0: 'SHT_NULL',
        1: 'SHT_PROGBITS',
        2: 'SHT_SYMTAB',
        3: 'SHT_STRTAB',
        4: 'SHT_RELA',
        5: 'SHT_HASH',
        6: 'SHT_DYNAMIC',
        7: 'SHT_NOTE',
        8: 'SHT_NOBITS',
        9: 'SHT_REL',
        10: 'SHT_SHLIB',
        11: 'SHT_DYNSYM',
    }
    
    has_rela = False
    has_rel = False
    
    for sec in sections:
        type_name = reloc_types.get(sec['sh_type'], f"SHT_???({sec['sh_type']})")
        sec_name = f"section[{sec['index']}]"
        
        if sec['sh_type'] == 4:  # SHT_RELA
            has_rela = True
            print(f"  ✓ Found .rela section at index {sec['index']}")
        elif sec['sh_type'] == 9:  # SHT_REL
            has_rel = True
            print(f"  ✓ Found .rel section at index {sec['index']}")
    
    if not has_rela and not has_rel:
        print("  ⚠️  No relocation sections found!")
        print("  External function calls will not be relocated by the linker.")

def main():
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <elf_file>")
        sys.exit(1)
    
    elf_path = Path(sys.argv[1])
    if not elf_path.exists():
        print(f"Error: File not found: {elf_path}")
        sys.exit(1)
    
    with open(elf_path, 'rb') as f:
        data = f.read()
    
    print(f"=== ELF Analysis: {elf_path} ===")
    print(f"File size: {len(data)} bytes (0x{len(data):x})")
    
    # Parse ELF header
    header = read_elf_header(data)
    if not header:
        print("Error: Invalid ELF file")
        sys.exit(1)
    
    print(f"\nELF Header:")
    print(f"  Type: {header['e_type']}")
    print(f"  Machine: {header['e_machine']}")
    print(f"  Entry: 0x{header['e_entry']:x}")
    print(f"  Section headers: offset=0x{header['e_shoff']:x}, count={header['e_shnum']}")
    
    # Parse section headers
    sections = read_section_headers(data, header['e_shoff'], header['e_shnum'], 64)
    
    # Find shstrtab
    shstrtab = None
    for sec in sections:
        if sec['index'] == header['e_shstrndx']:
            shstrtab = sec
            break
    
    if shstrtab:
        print(f"\n.shstrtab: offset=0x{shstrtab['sh_offset']:x}, size=0x{shstrtab['sh_size']:x}")
    
    # Print all sections
    print("\n=== Section Headers ===")
    for sec in sections:
        name = get_section_name(data, shstrtab['sh_offset'], sec['sh_name']) if shstrtab else f"[{sec['index']}]"
        type_name = {0: 'NULL', 1: 'PROGBITS', 2: 'SYMTAB', 3: 'STRTAB', 
                    4: 'RELA', 9: 'REL'}.get(sec['sh_type'], f"???({sec['sh_type']})")
        print(f"  [{sec['index']:2d}] {name:15s} {type_name:10s} offset=0x{sec['sh_offset']:06x} size=0x{sec['sh_size']:06x}")
    
    # Analyze external calls
    analyze_external_calls(data, sections)
    
    # Analyze relocations
    analyze_relocations(sections)
    
    print("\n=== Summary ===")
    print("To fix external function calls:")
    print("1. Add .rela.text section to ELF file")
    print("2. Create relocation entries for external function calls")
    print("3. Use R_X86_64_PLT32 relocation type for PLT calls")
    print("4. Change codegen to emit direct calls (E8) instead of indirect calls")

if __name__ == '__main__':
    main()
