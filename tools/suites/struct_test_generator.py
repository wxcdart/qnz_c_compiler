def generate_mixed_tests() -> str:
    """Generate tests with mixed argument types."""
    header = TEST_TEMPLATES['header']
    
    code = header + """
/* Mixed argument type tests */

typedef struct { int x; int y; } Pair8;
typedef struct { int a; int b; int c; } Triple12;

/* Struct + int arguments */
int struct_and_int(Pair8 p, int n) {
    return p.x + p.y + n;
}

/* Multiple structs */
int two_structs(Pair8 p1, Pair8 p2) {
    return p1.x + p1.y + p2.x + p2.y;
}

/* Struct + int + struct */
int mixed_args(Pair8 p1, int n, Pair8 p2) {
    return p1.x + n + p2.y;
}

/* Triple struct */
int take_triple(Triple12 t) {
    return t.a + t.b + t.c;
}

int make_and_take(void) {
    Triple12 t = {1, 2, 3};
    return take_triple(t);
}

int main(void) {
    /* Test struct + int */
    assert(struct_and_int((Pair8){10, 20}, 5) == 35);
    
    /* Test two structs */
    assert(two_structs((Pair8){1, 2}, (Pair8){3, 4}) == 10);
    
    /* Test mixed args */
    assert(mixed_args((Pair8){10, 20}, 5, (Pair8){30, 40}) == 75);
    
    /* Test triple struct */
    assert(make_and_take() == 6);
    
    return 0;
}
"""
    return code


def generate_nested_tests() -> str:
    """Generate tests with nested structs."""
    header = TEST_TEMPLATES['header']
    
    code = header + """
/* Nested struct tests */

typedef struct {
    int x;
    int y;
} Point;

typedef struct {
    Point center;
    int radius;
} Circle;

typedef struct {
    Circle c1;
    Circle c2;
} TwoCircles;

Point make_point(int x, int y) {
    Point p = {x, y};
    return p;
}

int get_point_x(Point p) {
    return p.x;
}

Circle make_circle(int x, int y, int r) {
    Circle c = {{x, y}, r};
    return c;
}

int get_circle_radius(Circle c) {
    return c.radius;
}

TwoCircles make_two_circles(int x1, int y1, int r1, int x2, int y2, int r2) {
    TwoCircles tc = {{{x1, y1}, r1}, {{x2, y2}, r2}};
    return tc;
}

int get_circle2_radius(TwoCircles tc) {
    return tc.c2.radius;
}

int main(void) {
    /* Test nested struct access */
    Circle c = make_circle(10, 20, 5);
    assert(get_circle_radius(c) == 5);
    
    /* Test deeply nested struct */
    TwoCircles tc = make_two_circles(1, 2, 3, 4, 5, 6);
    assert(get_circle2_radius(tc) == 6);
    
    return 0;
}
"""
    return code


def main():
    parser = argparse.ArgumentParser(description='Struct Test Generator for ZeroCC')
    parser.add_argument('--output', '-o', help='Output file path')
    parser.add_argument('--mode', '-m', choices=['args', 'returns', 'comprehensive', 
                          'mixed', 'nested', 'all'], default='comprehensive',
                        help='Test generation mode')
    
    args = parser.parse_args()
    
    # Generate tests based on mode
    if args.mode == 'args':
        code = generate_args_tests()
    elif args.mode == 'returns':
        code = generate_return_tests()
    elif args.mode == 'comprehensive':
        code = generate_comprehensive_tests()
    elif args.mode == 'mixed':
        code = generate_mixed_tests()
    elif args.mode == 'nested':
        code = generate_nested_tests()
    elif args.mode == 'all':
        # Generate all test files
        outputs = {
            'test_struct_args.c': generate_args_tests(),
            'test_struct_returns.c': generate_return_tests(),
            'test_structs_full.c': generate_comprehensive_tests(),
            'test_struct_mixed.c': generate_mixed_tests(),
            'test_struct_nested.c': generate_nested_tests(),
        }
        
        for filename, code in outputs.items():
            output_path = args.output.replace('.c', f'_{filename}') if args.output else f'test_{filename}'
            with open(output_path, 'w') as f:
                f.write(code)
            print(f"Generated: {output_path}")
        return
    
    else:
        code = generate_comprehensive_tests()
    
    # Write output
    if args.output:
        with open(args.output, 'w') as f:
            f.write(code)
        print(f"Generated: {args.output}")
    else:
        print(code)


if __name__ == '__main__':
    main()
