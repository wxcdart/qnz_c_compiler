#!/bin/sh
# musl_host_toolchain.sh -- build the VENDORED musl for the host and emit
# the static-musl gcc wrapper the Makefile uses to build zerocc itself.
#
# The goal: `build/bin/zerocc` (and every test binary that links the
# compiler library) is a fully STATIC binary against the vendored musl in
# third_party/vendor/musl/ - no host libc (glibc) dependency at runtime
# (ldd: "not a dynamic executable").
#
# musl has no dynamic loader: its dlopen/dlsym/dlclose/dlerror in libc.a
# are stubs that always fail ("Dynamic loading not supported"). The ZeroCC
# JIT needs runtime symbol resolution, so:
#   - the dlfcn members are STRIPPED from the installed libc.a, and
#   - zero_rt/dlfcn/dlfcn.c (host side, linked into zerocc before the
#     whole-archived libc) provides a working dlopen/dlsym/dlclose/dlerror
#     that resolves against the running executable's own ELF .symtab
#     (which, via --whole-archive, contains the entire musl libc).
#
# Produces (under $(BUILD_DIR)/musl - gitignored; the musl build itself is
# incremental via the in-tree obj/ cache, so rebuilds take seconds):
#   $(BUILD_DIR)/musl/lib/libc.a        static musl, dlfcn members stripped
#   $(BUILD_DIR)/musl/include/          musl headers (installed)
#   $(BUILD_DIR)/musl/lib/musl-gcc.specs
#   $(BUILD_DIR)/bin/musl-gcc           host wrapper (exec host gcc)
#
# Usage:
#   BUILD_DIR=build HOST_GCC=gcc sh tools/musl_host_toolchain.sh

set -eu

cd "$(dirname "$0")/.."

MUSL_DIR=third_party/vendor/musl/musl-1.2.6
BUILD_DIR="${BUILD_DIR:-build}"
HOST_GCC="${HOST_GCC:-gcc}"
PREFIX="${BUILD_DIR%/}/musl"
mkdir -p "$PREFIX"
PREFIX_ABS="$(cd "$PREFIX" && pwd)"

command -v "$HOST_GCC" >/dev/null 2>&1 || { echo "musl_host_toolchain: host cc '$HOST_GCC' not found" >&2; exit 1; }
[ -f "$MUSL_DIR/VERSION" ] || { echo "musl_host_toolchain: vendored musl missing at $MUSL_DIR" >&2; exit 1; }

echo "==> building static musl (host) from $MUSL_DIR"
(
  cd "$MUSL_DIR"
  CC="$HOST_GCC" ./configure --prefix="$PREFIX_ABS" --syslibdir="$PREFIX_ABS/lib" \
    --disable-shared --enable-optimize >/dev/null
  make -j"$(nproc)" AR=ar RANLIB=ranlib STRIP=strip >/dev/null
  make install AR=ar RANLIB=ranlib STRIP=strip >/dev/null
)
[ -f "$PREFIX_ABS/lib/libc.a" ] || { echo "musl_host_toolchain: libc.a missing after build" >&2; exit 1; }

# --- strip musl's dlfcn stubs: zero_rt/dlfcn/dlfcn.c supplies working
# --- dlopen/dlsym/dlclose/dlerror (self-ELF symtab resolution) and is
# --- linked ahead of the whole-archived libc, so these stubs must not
# --- collide with it.  dladdr/dlinfo/dl_iterate_phdr are stripped too:
# --- they depend on musl's dynamic-loader internals, which a static
# --- binary does not have; user code gets a clean "undefined reference"
# --- if it uses them (the virtual <dlfcn.h> only promises the core four).
LIBC="$PREFIX_ABS/lib/libc.a"
for m in dlopen.lo dlsym.lo __dlsym.lo dlclose.lo dlerror.lo dladdr.lo dlinfo.lo dl_iterate_phdr.lo; do
  if ar t "$LIBC" | grep -qx "$m"; then
    ar d "$LIBC" "$m"
  fi
done
ranlib "$LIBC"

# --- specs: full static-musl override (same proven structure as
# --- tools/setup_musl_cross.sh).  The empty *esp_* sections stop gcc from
# --- injecting its default glibc start files; -nostdlib lives in *link.
# musl's ldso soname matches the host arch (irrelevant for fully static
# links, but keep it correct).
case "$(uname -m)" in
  x86_64)  MUSL_ARCH=x86_64 ;;
  aarch64) MUSL_ARCH=aarch64 ;;
  riscv64) MUSL_ARCH=riscv64 ;;
  *) echo "musl_host_toolchain: unsupported host arch $(uname -m)" >&2; exit 1 ;;
esac
cat > "$PREFIX_ABS/lib/musl-gcc.specs" <<EOF
%rename cpp_options old_cpp_options

*cpp_options:
-nostdinc -isystem $PREFIX_ABS/include -isystem include%s %(old_cpp_options)

*cc1:
%(cc1_cpu) -nostdinc -isystem $PREFIX_ABS/include -isystem include%s

*link_libgcc:
-L$PREFIX_ABS/lib -L .%s

*libgcc:
libgcc.a%s %:if-exists(libgcc_eh.a%s)

*startfile:
%{!shared: $PREFIX_ABS/lib/Scrt1.o} $PREFIX_ABS/lib/crti.o crtbeginS.o%s

*endfile:
crtendS.o%s $PREFIX_ABS/lib/crtn.o

*link:
-dynamic-linker $PREFIX_ABS/lib/ld-musl-$MUSL_ARCH.so.1 -nostdlib %{shared:-shared} %{static:-static} %{rdynamic:-export-dynamic}

*esp_link:

*esp_options:

*esp_cpp_options:
EOF
# gcc's specs reader rejects an empty-valued spec at EOF; a trailing blank
# line (two newlines) after the final empty *esp_cpp_options: is required.
printf '\n\n' >> "$PREFIX_ABS/lib/musl-gcc.specs"

# --- wrapper: everything else (incl. -static -no-pie) comes from the
# --- caller; the specs carry -nostdinc/-isystem/crt/libc.
mkdir -p "$BUILD_DIR/bin"
cat > "$BUILD_DIR/bin/musl-gcc" <<EOF
#!/bin/sh
# host static-musl compiler wrapper (auto-generated by tools/musl_host_toolchain.sh)
exec "$HOST_GCC" "\$@" -specs "$PREFIX_ABS/lib/musl-gcc.specs"
EOF
chmod +x "$BUILD_DIR/bin/musl-gcc"

# --- sanity: the specs + stripped archive must still produce a working
# --- static binary (catches archive/specs regressions early).
cat > "$PREFIX_ABS/.sanity.c" <<'EOF'
#include <stdio.h>
#include <math.h>
int main(void) { printf("musl-ok %f\n", sqrt(4.0)); return 0; }
EOF
"$BUILD_DIR/bin/musl-gcc" -static -no-pie -O2 "$PREFIX_ABS/.sanity.c" \
  -Wl,--whole-archive "$LIBC" -Wl,--no-whole-archive \
  -o "$PREFIX_ABS/.sanity"
out="$("$PREFIX_ABS/.sanity")"
[ "$out" = "musl-ok 2.000000" ] || { echo "musl_host_toolchain: sanity check failed: $out" >&2; exit 1; }
rm -f "$PREFIX_ABS/.sanity.c" "$PREFIX_ABS/.sanity"

echo "    musl libc.a: $LIBC (dlfcn members stripped)"
echo "    wrapper:     $BUILD_DIR/bin/musl-gcc (host cc: $HOST_GCC)"
