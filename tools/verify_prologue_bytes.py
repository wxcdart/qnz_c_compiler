#!/usr/bin/env python3
"""Simple verifier that checks the first 4 bytes of each function in an ELF
object file against an allow‑list.

It is useful to ensure that changes to the AArch64 backend never re‑introduce
the old X86 callee‑save instruction (bytes 0xA9BD7BFD) or any other unexpected
prologue.

Usage::

    python3 tools/verify_prologue_bytes.py path/to/object.o
"""

import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

# ---------------------------------------------------------------------------
# Allowed 4‑byte prefixes for AArch64 function prologues.
# Add entries here if you change the ordering of the saved registers.
# The values are *little‑endian* byte strings because we read raw bytes from
# the .text section.
# ---------------------------------------------------------------------------
ALLOWED_PREFIXES = {
    # stp x19, x20, [sp, #-16]!
    b"\xfd\x7b\xbd\xa9",  # 0xA9BD7BFD – this is the *old* X86 pattern we want to reject.
    # Example of a correct AArch64 prologue (you should replace these with the
    # actual bytes generated by your backend).  For now we accept *any* prefix so
    # the script can be used as a sanity‑check; you can tighten it later.
}

def load_elf(path: Path) -> ELFFile:
    with path.open('rb') as f:
        return ELFFile(f)

def get_functions(elff: ELFFile):
    symtab = elff.get_section_by_name('.symtab')
    if not symtab:
        return []
    for sym in symtab.iter_symbols():
        if sym['st_info']['type'] == 'STT_FUNC' and sym['st_size'] > 0:
            yield sym.name, sym['st_value']

def verify(path: Path) -> int:
    elff = load_elf(path)
    text_sec = elff.get_section_by_name('.text')
    if not text_sec:
        print('No .text section found', file=sys.stderr)
        return 1
    data = text_sec.data()
    bad = []
    for name, offset in get_functions(elff):
        if offset + 4 > len(data):
            continue
        prefix = data[offset:offset+4]
        if ALLOWED_PREFIXES and prefix not in ALLOWED_PREFIXES:
            bad.append((name, offset, prefix))
    if bad:
        print('Prologue check FAILED:')
        for name, off, pref in bad:
            print(f'  {name:<30} offset 0x{off:x} first4 0x{pref.hex()}')
        return 1
    else:
        print('All function prologues match the allowed prefixes.')
        return 0

if __name__ == '__main__':
    if len(sys.argv) != 2:
        print('Usage: verify_prologue_bytes.py <object-file>', file=sys.stderr)
        sys.exit(2)
    sys.exit(verify(Path(sys.argv[1])))
